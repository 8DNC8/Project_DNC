/**
 ******************************************************************************
 * @file    HCSR04.h
 * @brief   HC-SR04超声波测距模块驱动 - 头文件(非阻塞EXTI版)
 *
 * ============================================================================
 *                              快速参考
 * ============================================================================
 *
 *   ┌─────────────────────────────────────────────────────────────┐
 *   │  STM32F103C8T6              HC-SR04                        │
 *   ├─────────────────────────────────────────────────────────────┤
 *   │  PB5 (输出)            ───►   Trig (触发信号)              │
 *   │  PB4 (EXTI4输入)       ◄───   Echo (回波信号)              │
 *   │  5V                    ───►   VCC                         │
 *   │  GND                   ───►   GND                          │
 *   └─────────────────────────────────────────────────────────────┘
 *
 *   测量范围: 2cm ~ 400cm
 *   返回单位: sonar_get_mm() 返回mm, -1=无效/超出范围
 *
 *   非阻塞用法:
 *     1. 初始化: HC_SR04_Init()
 *     2. 启动测量: sonar_start()       ← 非阻塞，约15μs返回
 *     3. 读取结果: sonar_get_mm()      ← 随时可读，-1=无效
 *     4. 超时保护: sonar_timeout_check() ← 主循环中每5ms调用
 *
 ******************************************************************************
 */

#ifndef __HCSR04_H                       // 防止重复包含
#define __HCSR04_H

#include "stm32f10x.h"                  // STM32标准库

/* ============================================================================
 *                              函数声明
 * ============================================================================ */

/**
 * @brief  初始化超声波模块(GPIO + EXTI)
 * @note  配置PB5 Trig输出, PB6 Echo EXTI双边沿输入
 */
void HC_SR04_Init(void);

/**
 * @brief  启动一次距离测量(非阻塞)
 * @note  发送Trig脉冲后立即返回，结果由EXTI中断自动更新
 *        约15μs返回，不阻塞主循环
 */
void sonar_start(void);

/**
 * @brief  获取最近一次测距结果
 * @return 距离(mm), >0=有效, -1=无效/超出范围/未测量
 * @note   非阻塞，直接读取上次测量结果
 */
int16_t sonar_get_mm(void);

/**
 * @brief  超时保护，需在主循环中每5ms调用一次
 * @note   如果测量状态卡住超过500ms，自动重置为无效
 */
void sonar_timeout_check(void);

/**
 * @brief  EXTI中断处理函数
 * @note   由stm32f10x_it.c中的EXTI9_5_IRQHandler调用
 *        在Echo上升沿记录时间，下降沿计算距离
 */
void HCSR04_EXTI_Handler(void);

#endif /* __HCSR04_H */
