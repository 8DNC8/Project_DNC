/**
 ******************************************************************************
 * @file    Encoder.h
 * @brief   编码器驱动 - MG310霍尔编码器 (TIM硬件正交编码模式)
 *
 * ============================================================================
 *                     MG310 霍尔编码器 引脚定义
 * ============================================================================
 *
 *   6P插座引脚   信号名称       线色      连接目标
 *   ────────    ──────────     ────      ──────────────────
 *     1         电机负极       棕/黑     接TB6612电机输出端(不走PCB编码器口)
 *     2         编码器供电VCC   红        5V (固定, 严禁接电池7.4/12V)
 *     3         编码器A相       绿        接STM32 PA8(左) / PB6(右)
 *     4         编码器B相       蓝        接STM32 PA9(左) / PB7(右)
 *     5         编码器GND       黑        GND (必须与STM32、驱动板共地!)
 *     6         电机正极       黄/红     接TB6612电机另一输出端(不走PCB编码器口)
 *
 *   重要: 你PCB上编码器口只引出4根 → 接 VCC(红) GND(黑) A相(绿) B相(蓝)
 *         电机动力线(1脚/6脚)走H桥, 不经过编码器口, 这是对的!
 *
 * ============================================================================
 *                         当前接线方案 (4线全接)
 * ============================================================================
 *
 *   左编码器:  VCC→5V   GND→GND   A相(绿)→PA8(TIM1_CH1)  B相(蓝)→PA9(TIM1_CH2)
 *   右编码器:  VCC→5V   GND→GND   A相(绿)→PB6(TIM4_CH1)  B相(蓝)→PB7(TIM4_CH2)
 *
 *   说明: 使用TIM1和TIM4硬件正交编码模式, 自动识别方向.
 *         A/B两相都接, 4倍频计数, 无需EXIT中断.
 *
 * ============================================================================
 *                         MG310 编码器参数
 * ============================================================================
 *
 *   MG310霍尔编码器基础脉冲: 11 PPR (电机轴每转)
 *   减速比常见: 1:30 或 1:50 (看电机标签)
 *
 *   输出轴每圈脉冲 = 11 × 减速比
 *     如1:30 → 330 PPR (输出轴)
 *     如1:50 → 550 PPR (输出轴)
 *
 *   TIM硬件编码器4倍频: 每圈计数值 = PPR × 4
 *     如1:30 → 1320 counts/rev
 *
 *   当前参数(需根据你的实际减速比校准):
 */

#ifndef __ENCODER_H
#define __ENCODER_H

#include "stm32f10x.h"

/* 编码器参数 — 根据你的MG310减速比调整! */
#define ENC_PPR             220     /* 输出轴每圈脉冲 (11PPR×20减速比) */
#define ENC_COUNTS_PER_REV   (ENC_PPR * 4)  /* 4倍频后每圈计数值 = 1320 */
#define WHEEL_DIA_MM        65      /* 车轮直径(mm) */
#define WHEEL_CIRC_MM       204     /* 车轮周长 = π×65 ≈ 204mm */
#define TRACK_WIDTH_MM      140     /* 轮距(两轮中心距, mm) */

/* 引脚定义 */
#define ENC_LEFT_PORT       GPIOA
#define ENC_LEFT_A_PIN      GPIO_Pin_8   /* PA8 → TIM1_CH1 左编码器A相(绿) */
#define ENC_LEFT_B_PIN      GPIO_Pin_9   /* PA9 → TIM1_CH2 左编码器B相(蓝) */

#define ENC_RIGHT_PORT      GPIOB
#define ENC_RIGHT_A_PIN     GPIO_Pin_6   /* PB6 → TIM4_CH1 右编码器A相(绿) */
#define ENC_RIGHT_B_PIN     GPIO_Pin_7   /* PB7 → TIM4_CH2 右编码器B相(蓝) */

/* 初始化编码器GPIO和TIM硬件正交编码 */
void Encoder_Init(void);

/* 每5ms调用一次，将TIM CNT增量累加到32位变量，防溢出 */
void Encoder_Update(void);

/* 获取编码器脉冲计数 (硬件4倍频, 正=前进/负=后退) */
int32_t Encoder_GetLeft(void);
int32_t Encoder_GetRight(void);

/* 获取行驶距离(左右轮平均, 单位0.1mm) */
int32_t Encoder_GetDistance(void);

/* 清零所有计数 */
void Encoder_Reset(void);

#endif /* __ENCODER_H */
