/**
 ******************************************************************************
 * @file    MPU6050.h
 * @brief   MPU6050六轴陀螺仪+加速度计驱动 - 头文件
 *
 * ============================================================================
 *                              快速参考
 * ============================================================================
 *
 *   ┌─────────────────────────────────────────────────────────────┐
 *   │  STM32F103C8T6              MPU6050                        │
 *   ├─────────────────────────────────────────────────────────────┤
 *   │  PB12              ───►   SCL (I2C时钟, 与OLED共用)       │
 *   │  PB13              ───►   SDA (I2C数据, 与OLED共用)       │
 *   │  3.3V              ───►   VCC (必须3.3V!)                   │
 *   │  GND               ───►   GND                              │
 *   │  GND               ───►   AD0 (地址=0xD0)                  │
 *   └─────────────────────────────────────────────────────────────┘
 *
 *   I2C地址: 0xD0(写) / 0xD1(读) (AD0接地)
 *
 *   测量范围:
 *     陀螺仪: ±500°/s
 *     加速度计: ±4g
 *
 *   灵敏度:
 *     陀螺仪: 65.5 LSB/(°/s)
 *     加速度计: 8192 LSB/g
 *
 ******************************************************************************
 */

#ifndef __MPU6050_H                      // 防止重复包含
#define __MPU6050_H

#include "stm32f10x.h"                  // STM32标准库

/* ============================================================================
 *                              数据结构
 * ============================================================================ */

/**
 * @brief  MPU6050原始数据
 */
typedef struct {
    int16_t accel_x;                   // 【X轴加速度】原始值
    int16_t accel_y;                   // 【Y轴加速度】原始值
    int16_t gyro_z;                    // 【Z轴角速度】原始值，已去零偏
} MPU6050_Data_t;

/* ============================================================================
 *                              函数声明
 * ============================================================================ */

/**
 * @brief  初始化MPU6050
 * @note  包含零偏校准，校准时芯片必须静止！
 */
void MPU6050_Init(void);

/**
 * @brief  检测MPU6050是否在线
 * @return 1=在线, 0=离线
 */
uint8_t MPU6050_Check(void);

/**
 * @brief  读取完整传感器数据
 * @param  data - 数据结构指针
 */
void MPU6050_ReadData(MPU6050_Data_t *data);

/**
 * @brief  读取Z轴角速度(原始值，已去零偏)
 * @return 角速度原始值
 */
int16_t MPU6050_GetGyroZ(void);

/**
 * @brief  读取Z轴角速度(°/s)
 * @return 角速度值，单位°/s
 */
float MPU6050_GetGyroZ_Deg(void);

#endif /* __MPU6050_H */
