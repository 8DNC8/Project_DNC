/**
 ******************************************************************************
 * @file    Delay.h
 * @brief   SysTick延时函数 - 头文件
 *
 * ============================================================================
 *                              延时范围
 * ============================================================================
 *
 *   函数              最大延时
 *   ──────────────────────────────────────
 *   Delay_us(xus)    ~233ms (72MHz系统时钟)
 *   Delay_ms(xms)    ~233s
 *   Delay_s(xs)      ~233s
 *
 * ============================================================================
 */

#ifndef __DELAY_H                        // 防止重复包含
#define __DELAY_H

#include "stm32f10x.h"                  // STM32标准库

/* ============================================================================
 *                              函数声明
 * ============================================================================ */

/**
 * @brief  微秒级延时
 * @param  us - 延时时长(微秒)
 * @note   精确延时，范围: 0~233015
 */
void Delay_us(uint32_t us);

/**
 * @brief  毫秒级延时
 * @param  ms - 延时时长(毫秒)
 * @note   范围: 0~4294967295 (约49天)
 */
void Delay_ms(uint32_t ms);

/**
 * @brief  秒级延时
 * @param  s - 延时时长(秒)
 */
void Delay_s(uint32_t s);

#endif /* __DELAY_H */
