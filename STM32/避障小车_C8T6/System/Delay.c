/**
 ******************************************************************************
 * @file    Delay.c
 * @brief   SysTick延时函数实现
 *
 * ============================================================================
 *                          SysTick定时器
 * ============================================================================
 *
 *   SysTick是ARM Cortex-M3内核自带的24位递减定时器
 *   广泛用于操作系统心跳和精确延时
 *
 *   ┌─────────────────────────────────────────────────────────────┐
 *   │                    SysTick结构                              │
 *   │                                                             │
 *   │  CTRL ───► 控制和状态寄存器                                │
 *   │  LOAD ───► 重装载值寄存器                                  │
 *   │  VAL  ───► 当前值寄存器                                    │
 *   │  CALIB ──► 校准寄存器                                      │
 *   │                                                             │
 *   │  时钟源: HCLK = 72MHz (本项目配置)                         │
 *   │                                                             │
 *   └─────────────────────────────────────────────────────────────┘
 *
 * ============================================================================
 *                          延时原理
 * ============================================================================
 *
 *   SysTick配置为递减模式:
 *     1. 设置重装载值LOAD
 *     2. 计数器从LOAD值开始递减
 *     3. 递减到0时，产生更新标志
 *     4. 重新装载LOAD，循环
 *
 *   ┌─────────────────────────────────────────────────────────────┐
 *   │                    SysTick递减过程                          │
 *   │                                                             │
 *   │  LOAD ──► 99999...3,2,1,0 ──► 重新装载LOAD ──► 循环       │
 *   │              ↓                                            │
 *   │         递减计数                                           │
 *   │              ↓                                            │
 *   │         VAL寄存器                                          │
 *   │                                                             │
 *   │  每计数一次 = 1/72MHz ≈ 13.9ns                             │
 *   │  计数到0 = (LOAD+1) × 13.9ns                               │
 *   │                                                             │
 *   └─────────────────────────────────────────────────────────────┘
 *
 * ============================================================================
 *                          本项目延时范围
 * ============================================================================
 *
 *   SysTick为24位，最大计数2^24 = 16777215
 *
 *   us延时:  最高 16777215 / 72 ≈ 233ms
 *   ms延时:  最高 16777215 / 72000 ≈ 233秒
 *
 *   足够满足循迹小车的延时需求(通常<1秒)
 *
 ******************************************************************************
 */

#include "stm32f10x.h"                  // STM32标准库

/* DWT寄存器 (CMSIS旧版未包含) */
#define DWT_CYCCNT  (*(volatile uint32_t *)0xE0001004)

/**
 * @brief  微秒级延时
 * @param  xus - 延时时长(微秒)
 * @note   使用DWT周期计数器, 不干扰SysTick
 */
void Delay_us(uint32_t xus)
{
    uint32_t target = 72 * xus;  /* HCLK=72MHz, 72ticks/us */
    uint32_t start  = DWT_CYCCNT;
    while ((DWT_CYCCNT - start) < target);
}

/**
 * @brief  毫秒级延时
 * @param  xms - 延时时长(毫秒)
 * @note   内部调用Delay_us()
 */
void Delay_ms(uint32_t xms)
{
    /* 循环xms次，每次延时1ms */
    while(xms--)
    {
        Delay_us(1000);                 // 1ms = 1000μs
    }
}

/**
 * @brief  秒级延时
 * @param  xs - 延时时长(秒)
 * @note   内部调用Delay_ms()
 */
void Delay_s(uint32_t xs)
{
    /* 循环xs次，每次延时1秒 */
    while(xs--)
    {
        Delay_ms(1000);                 // 1s = 1000ms
    }
}
